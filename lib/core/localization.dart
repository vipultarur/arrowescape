  String translate(String key) {
    final langMap = _localizedValues[language] ?? _localizedValues['English']!;
    return langMap[key] ?? _localizedValues['English']![key] ?? key;
  }

  static String tr(BuildContext context, String key) {
    final state = AppLocalizations.of(context);
    return state.translate(key);
  }

  static AppLocalizations of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<_AppLocalizationsScope>();
    return scope?.localizations ?? AppLocalizations('English');
  }
}

class _AppLocalizationsScope extends InheritedWidget {
  final AppLocalizations localizations;

  const _AppLocalizationsScope({
    required this.localizations,
    required super.child,
  });

  @override
  bool updateShouldNotify(_AppLocalizationsScope oldWidget) {
    return oldWidget.localizations.language != localizations.language;
  }
}

class AppLocalizationWrapper extends StatelessWidget {
  final String language;
  final Widget child;

  const AppLocalizationWrapper({
    super.key,
    required this.language,
    required this.child,
  });

  @override
  Widget build(BuildContext context) {
    return _AppLocalizationsScope(
      localizations: AppLocalizations(language),
      child: child,
    );
  }
}

extension LocalizationExtension on BuildContext {
  String tr(String key) => AppLocalizations.tr(this, key);
}
